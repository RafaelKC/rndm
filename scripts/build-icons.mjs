// Builds a tiny Tabler icon font with only the icons listed in scripts/icons.json:
//   public/fonts/tabler-icons-subset.woff2  (a few hundred bytes instead of ~500 kB)
//   src/icons.css                           (the .ti base class + one class per icon)
// To use a new icon: add its name (e.g. "brand-github") to scripts/icons.json and run `pnpm icons`.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import subsetFont from 'subset-font';
import { ROOT } from './posts-lib.mjs';

const dist = join(ROOT, 'node_modules/@tabler/icons-webfont/dist');
const names = JSON.parse(readFileSync(join(import.meta.dirname, 'icons.json'), 'utf8'));
const css = readFileSync(join(dist, 'tabler-icons.css'), 'utf8');

const glyphs = names.map((name) => {
  const match = css.match(new RegExp(`\\.ti-${name.replace(/[-]/g, '\\-')}:before\\s*\\{\\s*content:\\s*"\\\\([0-9a-f]+)"`, 'i'));
  if (!match) throw new Error(`Unknown Tabler icon: "${name}"`);
  return { name, code: match[1] };
});

const text = glyphs.map((g) => String.fromCodePoint(parseInt(g.code, 16))).join('');
const font = await subsetFont(readFileSync(join(dist, 'fonts/tabler-icons.ttf')), text, { targetFormat: 'woff2' });
mkdirSync(join(ROOT, 'public/fonts'), { recursive: true });
writeFileSync(join(ROOT, 'public/fonts/tabler-icons-subset.woff2'), font);

writeFileSync(
  join(ROOT, 'src/icons.css'),
  `/* Generated by scripts/build-icons.mjs (pnpm icons). Do not edit by hand. */
@font-face {
  font-family: "tabler-icons";
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url("/fonts/tabler-icons-subset.woff2") format("woff2");
}

.ti {
  font-family: "tabler-icons" !important;
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${glyphs.map((g) => `.ti-${g.name}:before {\n  content: "\\${g.code}";\n}`).join('\n\n')}
`,
);
console.log(`icons: ${glyphs.length} icon(s), font ${font.length} bytes`);
